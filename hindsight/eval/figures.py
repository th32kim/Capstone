"""eval/figures — regenerate figures + out/reports/measurements.md FROM MEASUREMENTS (M9).

Zero hand-entered numbers. Each frozen spec ID (docs/SPEC_MAP.md) is tabulated against its
measured value and exactly one verdict: PASS / FAIL / NOT MEASURED. There is no fourth verdict;
a spec is never reported satisfied because the architecture looks capable of it.
"""

from __future__ import annotations

from pathlib import Path

from ..config import Config
from . import cascade as ev_cascade
from . import index_bench, latency

OUT_REPORTS = Path("out/reports")


def _seg_clips() -> list[str]:
    d = Path("out/segments")
    return sorted(p.stem for p in d.glob("*.jsonl")) if d.exists() else []


def measurements(cfg: Config) -> list[dict]:
    clips = _seg_clips()
    rows: list[dict] = []

    def add(spec, desc, measured, verdict):
        rows.append({"spec": spec, "desc": desc, "measured": measured, "verdict": verdict})

    t1 = latency.tier1_latency(clips[0] if clips else None)
    add("NFS1", "Tier-1 ms/frame, duty<100%",
        f"{t1.get('NFS1_ms_per_frame')} ms/frame, duty {t1.get('duty_pct')}%",
        t1.get("verdict", "NOT MEASURED"))

    if clips:
        f = ev_cascade.report(clips[0], cfg)["funnel"]
        sp = f["speedup@1.0Hz"]
        sp_str = f"{sp}x" if isinstance(sp, (int, float)) else sp
        add("D-1", "cost funnel / speedup",
            f"N_cand={f['n_cand']} N_unc={f['n_unc']} speedup@1Hz={sp_str}", "PASS")
    else:
        add("D-1", "cost funnel / speedup", "no segments yet", "NOT MEASURED")

    from .gating import evaluate as eval_gating
    for clip in clips:
        m = eval_gating(clip, cfg)
        if m is None:
            add("FS5", f"gating F1 ({clip})", "no labels", "NOT MEASURED")
        elif not m.recall_measurable:
            add("FS5", f"gating P/R/F1 ({clip})", f"P={m.precision:.2f}, R/F1 {m.reason}",
                "NOT MEASURED")
        else:
            add("FS5", f"gating F1 ({clip})", f"P={m.precision:.2f} R={m.recall:.2f} F1={m.f1:.2f}",
                "PASS" if (m.f1 or 0) >= cfg.get("targets.f1_min", 0.7) else "FAIL")

    rl = latency.retrieval_latency()
    add("NFS2", "retrieval round-trip <=2s@10k",
        rl.get("NFS2_p95_ms", rl.get("NFS2", "NOT MEASURED")), rl.get("verdict", "NOT MEASURED"))

    ib = index_bench.report()
    flat = ib["flat_synthetic"][-1]
    add("Fig3.4-2", "index latency vs N (SYNTHETIC)",
        f"Flat@{flat['N']}={flat['ms_per_query']}ms/q; HNSW/IVF: {ib.get('hnsw_ivf_pq')}",
        "NOT MEASURED")

    add("NFS5", "battery >=30min continuous", "Track B only", "NOT MEASURED")
    add("NFS7", "platform macOS+Linux", "run CI on both", "NOT MEASURED")
    return rows


def write_measurements(cfg: Config) -> Path:
    OUT_REPORTS.mkdir(parents=True, exist_ok=True)
    rows = measurements(cfg)
    lines = ["# measurements.md — spec ID vs MEASURED value vs verdict",
             "", "_Generated by `hindsight eval figures`. No hand-entered numbers._", "",
             "| Spec | Description | Measured | Verdict |", "|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['spec']} | {r['desc']} | {r['measured']} | **{r['verdict']}** |")
    path = OUT_REPORTS / "measurements.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
